@bp.route("/api/report/<rid>/correction/execute", methods=["POST"])
def execute_correction(rid: str):
    from app import scanner as scanner_mod
    from app import targets as targets_mod

    r = store.get(rid)
    if r is None:
        abort(404)

    data = request.get_json(silent=True) or {}
    fmt = (data.get("format") or "ansible").lower()
    rule_ids = set(data.get("rules") or [])
    if not rule_ids:
        return jsonify({"error": "No rules selected."}), 400

    source = r.get("source", "")
    if not source.startswith("ssh:"):
        return jsonify({"error": "Execute is only available for reports collected via SSH scan."}), 400

    host = source.replace("ssh:", "").strip()
    target = next((t for t in targets_mod.all_targets() if t["host"] == host), None)
    if target is None:
        return jsonify({
            "error": f"No SSH target configured for '{host}'. Add it in the Scan tab first."
        }), 400

    selected = [rule for rule in (r.get("rules") or []) if rule.get("id") in rule_ids]
    ts = int(_time.time())

    if fmt == "ansible":
        content = _generate_ansible(selected, r)
        remote_path = f"/tmp/_oscap_remediation_{ts}.yml"
        exec_cmd = f"ansible-playbook -i 'localhost,' -c local '{remote_path}' 2>&1"
    else:
        content = _generate_bash(selected, r)
        remote_path = f"/tmp/_oscap_remediation_{ts}.sh"
        exec_cmd = f"bash '{remote_path}' 2>&1"

    try:
        client = scanner_mod._connect(target)
        with client.open_sftp() as sftp:
            with sftp.file(remote_path, "w") as fobj:
                fobj.write(content)
            sftp.chmod(remote_path, 0o700)

        rc, stdout, stderr = scanner_mod._exec(client, exec_cmd, timeout=300)
        scanner_mod._exec(client, f"rm -f '{remote_path}'", timeout=10)
        client.close()

        return jsonify({
            "exit_code": rc,
            "stdout": stdout,
            "stderr": stderr,
            "success": rc == 0,
        })
    except Exception as exc:
        return jsonify({"error": str(exc)}), 500


