def _generate_bash(rules: list, report: dict) -> str:
    hostname = report.get('hostname', 'unknown')
    sep = '# ' + '=' * 72
    lines = [
        "#!/usr/bin/env bash",
        "#",
        "# OpenSCAP Remediation Script",
        f"# Host:    {hostname}",
        f"# Profile: {report.get('profile', '')}",
        f"# Date:    {report.get('scan_date', '')}",
        f"# Rules:   {len(rules)}",
        "#",
        "# Generated by OpenSCAP Dashboard",
        "#",
        "set -euo pipefail",
        "",
    ]
    for rule in rules:
        fix = (rule.get('fix_bash') or '').strip()
        lines += [
            sep,
            f"# {rule.get('title', rule['id'])[:72]}",
            f"# Severity: {rule.get('severity', 'unknown')}",
            f"# Rule:     {rule['id']}",
            sep,
        ]
        if fix:
            lines.append(fix)
        else:
            lines.append(
                "# ⚠  No automated bash remediation available"
                " — manual action required."
            )
        lines.append("")
    return "\n".join(lines)


def _generate_ansible(rules: list, report: dict) -> str:
    hostname = report.get('hostname', 'unknown')
    sep = '    # ' + '=' * 68
    lines = [
        "---",
        "# OpenSCAP Remediation Playbook",
        f"# Host:    {hostname}",
        f"# Profile: {report.get('profile', '')}",
        f"# Date:    {report.get('scan_date', '')}",
        f"# Rules:   {len(rules)}",
        "#",
        "# Generated by OpenSCAP Dashboard",
        "",
        f"- name: \"OpenSCAP Remediation — {hostname}\"",
        "  hosts: all",
        "  become: true",
        "  tasks:",
        "",
    ]
    for rule in rules:
        fix = (rule.get('fix_ansible') or '').strip()
        title = rule.get('title', rule['id'])
        lines += [sep, f"    # {title[:68]}", f"    # Severity: {rule.get('severity', 'unknown')} | {rule['id']}", sep]
        if fix:
            lines.append(f"    - name: \"Remediate: {title[:55]}\"")
            lines.append("      block:")
            for line in fix.split('\n'):
                lines.append(f"        {line}")
            lines.append("      rescue:")
            lines.append(f"        - name: \"Skipped (failed): {title[:52]}\"")
            lines.append("          ansible.builtin.debug:")
            lines.append("            msg: >-")
            lines.append(f"              Remediation skipped for rule '{rule['id']}'.")
            lines.append("              Failed task: {{ ansible_failed_task.name }}.")
            lines.append("              Error: {{ ansible_failed_result.msg | default('see logs') }}")
        else:
            lines += [
                f"    - name: \"MANUAL REMEDIATION: {title[:52]}\"",
                "      ansible.builtin.debug:",
                f"        msg: \"No automated fix — manually remediate: {rule['id']}\"",
            ]
        lines.append("")
    return "\n".join(lines)


